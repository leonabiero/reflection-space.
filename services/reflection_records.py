def _management_filters(date_filter, tag):
    conditions = [NOT_IN_DELETION_WINDOW]
    params = []
    if date_filter:
        conditions.append("r.created_at::date = %s")
        params.append(date_filter)
    if tag and tag in CASE_TAGS:
        # case_tags is a JSON list of known keys, so the quoted key can
        # only match that exact tag.
        conditions.append("r.case_tags LIKE %s")
        params.append(f'%"{tag}"%')
    return " AND ".join(conditions), params


def list_reflections(actor_role, date_filter=None, tag=None, limit=50, offset=0):
    """
    Organisation-wide list of saved reflections, newest first, for the
    management Case History screen. Management roles only (returns []
    otherwise). Each item: run_id, code, case_tags, note_type,
    created_by, created_by_role, created_at, finding_count.
    """
    if not require_management_role(actor_role):
        return []
    limit = max(1, min(int(limit), 500))
    offset = max(0, int(offset))
    where, params = _management_filters(date_filter, tag)
    conn = _get_conn()
    try:
        with conn.cursor() as c:
            c.execute(
                f"""
                SELECT r.id, COALESCE(r.reflection_code, r.case_ref), r.case_tags,
                       r.note_type, r.created_by, r.created_by_role, r.created_at,
                       (SELECT COUNT(*) FROM reflection_findings f WHERE f.run_id = r.id),
                       r.previous_code
                FROM reflection_runs r
                WHERE {where}
                ORDER BY r.created_at DESC, r.id DESC
                LIMIT %s OFFSET %s
                """,
                (*params, limit, offset),
            )
            rows = c.fetchall()
    finally:
        conn.close()
    return [
        {
            "run_id": r[0],
            "code": r[1] or "",
            "case_tags": _loads_list(r[2]),
            "note_type": r[3] or "",
            "created_by": r[4] or "",
            "created_by_role": r[5] or "",
            "created_at": iso(r[6]),
            "finding_count": r[7] or 0,
            "previous_code": r[8] or "",
        }
        for r in rows
    ]


def count_reflections(actor_role, date_filter=None, tag=None):
    """How many reflections match the same filters as list_reflections()."""
    if not require_management_role(actor_role):
        return 0
    where, params = _management_filters(date_filter, tag)
    conn = _get_conn()
    try:
        with conn.cursor() as c:
            c.execute(f"SELECT COUNT(*) FROM reflection_runs r WHERE {where}", tuple(params))
            return c.fetchone()[0]
    finally:
        conn.close()


def get_reflection_dates(actor_role):
    """Distinct calendar dates ('YYYY-MM-DD', newest first) with at least
    one saved reflection -- for the Case History date filter."""
    if not require_management_role(actor_role):
        return []
    conn = _get_conn()
    try:
        with conn.cursor() as c:
            c.execute(
                f"""
                SELECT DISTINCT r.created_at::date AS d
                FROM reflection_runs r
                WHERE {NOT_IN_DELETION_WINDOW}
                ORDER BY d DESC
                """
            )
            rows = c.fetchall()
    finally:
        conn.close()
    return [row[0].isoformat() for row in rows]


def get_findings_for_reflections(actor_role, run_ids):
    """The AI's findings for several reflections in ONE query, as
    {run_id: [{id, module, observation, questions, evidence,
    unverified_quote_count}, ...]}. Management roles only. Never includes
    anyone's private notes."""
    ids = [int(r) for r in (run_ids or [])]
    if not require_management_role(actor_role) or not ids:
        return {}
    conn = _get_conn()
    try:
        with conn.cursor() as c:
            c.execute(
                """
                SELECT run_id, id, module, observation, questions, evidence, unverified_quote_count
                FROM reflection_findings
                WHERE run_id = ANY(%s)
                ORDER BY run_id, id
                """,
                (ids,),
            )
            rows = c.fetchall()
    finally:
        conn.close()
    results = {}
    for r in rows:
        try:
            evidence = json.loads(r[5]) if r[5] else []
        except (TypeError, ValueError):
            evidence = []
        results.setdefault(r[0], []).append({
            "id": r[1],
            "module": r[2],
            "observation": r[3] or "",
            "questions": _loads_list(r[4]),
            "evidence": evidence if isinstance(evidence, list) else [],
            "unverified_quote_count": r[6] or 0,
        })
    return results


def get_reflection_findings(actor_role, run_id):
    """The AI's findings for one reflection (see
    get_findings_for_reflections)."""
    if not run_id:
        return []
    return get_findings_for_reflections(actor_role, [run_id]).get(int(run_id), [])


def delete_reflection(run_id, actor_name, actor_role):
    """
    Permanently delete one reflection with all its findings and the
    professional's notes on them (ON DELETE CASCADE). System
    Administrator only -- the same role that could delete cases before
    this redesign. Returns True if something was deleted.
    """
    if actor_role != "System Administrator" or not actor_name or not run_id:
        return False
    conn = _get_conn()
    try:
        with conn.cursor() as c:
            c.execute(
                "SELECT COALESCE(reflection_code, case_ref) FROM reflection_runs WHERE id = %s",
                (run_id,),
            )
            row = c.fetchone()
            if not row:
                conn.rollback()
                return False
            code = row[0] or ""
            c.execute("DELETE FROM reflection_runs WHERE id = %s", (run_id,))
            # A pattern left with no observations at all loses its
            # explanation too (same rule as findings_store.delete_runs_for_drafts).
            c.execute("SELECT to_regclass('patterns')")
            if c.fetchone()[0] is not None:
                c.execute(
                    """
                    DELETE FROM patterns p
                    WHERE p.original_member_count > 0
                      AND NOT EXISTS (SELECT 1 FROM pattern_findings pf WHERE pf.pattern_id = p.id)
                    """
                )
        conn.commit()
    except Exception:
        conn.rollback()
        logger.exception("delete_reflection FAILED: run_id=%r", run_id)
        raise
    finally:
        conn.close()

    try:
        from services.audit_log import log_action
        log_action("purged", None, code, "reflection", actor_name, actor_role,
                   details="reflection deleted")
    except Exception:
        logger.exception("delete_reflection: audit log failed for run_id=%r", run_id)
    return True


