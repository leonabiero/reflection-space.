def get_own_reflection(code, owner_name):
    """The professional's OWN reflection with this code, as a small dict
    (no observations), or None if it doesn't exist or isn't theirs."""
    code = normalize_code(code)
    if not code or not owner_name:
        return None
    conn = _get_conn()
    try:
        with conn.cursor() as c:
            c.execute(
                f"""
                SELECT r.id, r.reflection_code, r.case_tags, r.note_type,
                       r.previous_code, r.created_at
                FROM reflection_runs r
                WHERE r.reflection_code = %s AND r.created_by = %s
                  AND {NOT_IN_DELETION_WINDOW}
                """,
                (code, owner_name),
            )
            row = c.fetchone()
    finally:
        conn.close()
    if not row:
        return None
    return {
        "run_id": row[0],
        "code": row[1],
        "case_tags": _loads_list(row[2]),
        "note_type": row[3] or "",
        "previous_code": row[4] or "",
        "created_at": iso(row[5]),
    }


def _observations_for_runs(cursor, run_ids):
    """{run_id: [{"module", "observation"}, ...]} -- observations only,
    never quotes or notes."""
    if not run_ids:
        return {}
    cursor.execute(
        """
        SELECT run_id, module, observation
        FROM reflection_findings
        WHERE run_id = ANY(%s)
        ORDER BY run_id, id
        """,
        (list(run_ids),),
    )
    result = {}
    for run_id, module, observation in cursor.fetchall():
        if observation:
            result.setdefault(run_id, []).append({"module": module, "observation": observation})
    return result


def find_similar_reflections(owner_name, case_tags=None, previous_code="",
                             limit=SIMILAR_LIMIT, exclude_code=""):
    """
    The professional's OWN earlier reflections worth offering as context
    for a new one, best first:

    1. "linked"  -- the reflection named in `previous_code` (if it is
       theirs), and up to LINK_CHAIN_DEPTH steps further back along its
       own previous_code links;
    2. "tags"    -- other reflections of theirs sharing at least one case
       tag, most shared tags first, then most recent.

    Returns a list of dicts: run_id, code, case_tags, note_type,
    created_at, match_reasons (["linked"] / ["tags"] / both),
    shared_tags, observations ([{"module", "observation"}]).
    Reflections with no observations at all are skipped (nothing to
    offer as context).
    """
    if not owner_name:
        return []
    tags = set(clean_tags(case_tags))
    exclude_code = normalize_code(exclude_code)

    conn = _get_conn()
    try:
        with conn.cursor() as c:
            c.execute(
                f"""
                SELECT r.id, r.reflection_code, r.case_tags, r.note_type,
                       r.previous_code, r.created_at
                FROM reflection_runs r
                WHERE r.created_by = %s AND r.reflection_code IS NOT NULL
                  AND {NOT_IN_DELETION_WINDOW}
                ORDER BY r.created_at DESC
                LIMIT %s
                """,
                (owner_name, _SIMILAR_SCAN_LIMIT),
            )
            rows = c.fetchall()

            by_code = {}
            candidates = []
            for run_id, code, tags_json, note_type, prev, created_at in rows:
                if code == exclude_code:
                    continue
                record = {
                    "run_id": run_id,
                    "code": code,
                    "case_tags": _loads_list(tags_json),
                    "note_type": note_type or "",
                    "previous_code": prev or "",
                    "created_at": iso(created_at),
                    "match_reasons": [],
                    "shared_tags": [],
                }
                by_code[code] = record
                candidates.append(record)

            # 1. Linked chain.
            linked_order = []
            next_code = normalize_code(previous_code)
            seen = set()
            while next_code and next_code in by_code and next_code not in seen \
                    and len(linked_order) < LINK_CHAIN_DEPTH:
                seen.add(next_code)
                record = by_code[next_code]
                record["match_reasons"].append("linked")
                linked_order.append(record)
                next_code = record["previous_code"]

            # 2. Shared tags.
            for record in candidates:
                shared = [t for t in CASE_TAGS if t in tags and t in record["case_tags"]]
                if shared:
                    record["shared_tags"] = shared
                    record["match_reasons"].append("tags")

            tagged = [r for r in candidates if "tags" in r["match_reasons"] and r not in linked_order]
            # candidates are already newest first; a stable sort keeps that
            # order among reflections sharing the same number of tags.
            tagged.sort(key=lambda r: len(r["shared_tags"]), reverse=True)

            ordered = linked_order + tagged
            observations = _observations_for_runs(c, [r["run_id"] for r in ordered])
    finally:
        conn.close()

    results = []
    for record in ordered:
        obs = observations.get(record["run_id"])
        if not obs:
            continue
        record["observations"] = obs
        results.append(record)
        if len(results) >= limit:
            break

    logger.info(
        "find_similar_reflections: owner=%r tags=%d linked=%s -> %d result(s)",
        owner_name, len(tags), bool(previous_code), len(results),
    )
    return results


def build_context_block(similar):
    """
    Plain text describing the included earlier reflections, appended
    after today's case text before it is sent to the AI (the whole text
    is anonymised again by rdi/orchestrator.py). Internal, never shown
    on screen, so it is written in English like the rest of the prompt
    scaffolding.
    """
    if not similar:
        return ""
    lines = [
        "=== EARLIER REFLECTIONS (context only) ===",
        "The professional's own earlier reflections on a linked or similar "
        "situation. They are NOT part of today's case text; use them only to "
        "notice continuity, recurring themes or changes.",
    ]
    for i, record in enumerate(similar, start=1):
        date = (record.get("created_at") or "")[:10]
        reasons = "+".join(record.get("match_reasons") or [])
        themes = ", ".join(record.get("case_tags") or []) or "-"
        lines.append("")
        lines.append(f"[{i}] code={record.get('code')} date={date} link={reasons} themes={themes}")
        for obs in record.get("observations") or []:
            lines.append(f"- {obs['module']}: {obs['observation']}")
    lines.append("=== END OF EARLIER REFLECTIONS ===")
    return "\n".join(lines)


