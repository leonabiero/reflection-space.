# ---------------------------------------------------------------------
# Case tags -- non-personal themes describing the SITUATION, never the
# person. Labels live in the translation files under "case_tag_labels"
# (services/locales/*.py); keep the two in step. Order here is the order
# shown on screen.
# ---------------------------------------------------------------------
CASE_TAGS = (
    "housing",
    "employment_training",
    "income_benefits",
    "mental_health",
    "physical_health",
    "addictions",
    "disability",
    "family_relationships",
    "children_youth",
    "older_people",
    "gender_violence",
    "social_isolation",
    "migration_integration",
    "legal_administrative",
)

MAX_TAGS = 6

# ---------------------------------------------------------------------
# Reflection codes
# ---------------------------------------------------------------------
CODE_PREFIX = "RS-"
CODE_LENGTH = 6
# No 0/O, 1/I/L: codes are read aloud and copied by hand.
_CODE_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789"
_CODE_RE = re.compile(rf"^RS-[{_CODE_ALPHABET}]{{{CODE_LENGTH}}}$")

# How many earlier reflections can be offered as context at once, and
# how far back along a previous_code chain we follow.
SIMILAR_LIMIT = 5
LINK_CHAIN_DEPTH = 3
_SIMILAR_SCAN_LIMIT = 300

# Knowledge Assistant evidence search.
_EVIDENCE_SCAN_LIMIT = 400


def _get_conn():
    """Pooled connection (services/db_pool.py). Tables are created once
    at startup by services/db_schema.py:ensure_schema()."""
    return _acquire_pooled_conn()


def _loads_list(value):
    try:
        loaded = json.loads(value) if value else []
    except (TypeError, ValueError):
        return []
    return [str(x) for x in loaded] if isinstance(loaded, list) else []


# ---------------------------------------------------------------------
# Codes and tags
# ---------------------------------------------------------------------

def generate_code():
    """A fresh random code such as RS-7F3K2Q (not checked against the
    database -- see new_reflection_code())."""
    return CODE_PREFIX + "".join(secrets.choice(_CODE_ALPHABET) for _ in range(CODE_LENGTH))


def is_valid_code(code):
    return bool(code) and bool(_CODE_RE.match(code))


def normalize_code(raw):
    """Tidy what a person typed into a code: trims, upper-cases, removes
    spaces, and adds the RS- prefix if only the six characters were
    typed. Returns "" if the result is not a valid code."""
    if not raw:
        return ""
    text = re.sub(r"\s+", "", str(raw)).upper()
    if not text.startswith(CODE_PREFIX) and len(text) == CODE_LENGTH:
        text = CODE_PREFIX + text
    return text if is_valid_code(text) else ""


def code_exists(code):
    conn = _get_conn()
    try:
        with conn.cursor() as c:
            c.execute("SELECT 1 FROM reflection_runs WHERE reflection_code = %s LIMIT 1", (code,))
            return c.fetchone() is not None
    finally:
        conn.close()


def new_reflection_code(max_attempts=8):
    """A code not yet used by any reflection. With 31^6 (~887 million)
    possible codes a clash is extremely unlikely; the database's unique
    index is the final guarantee. If the database cannot be reached the
    random code is returned anyway (the save step will then report its
    own failure honestly)."""
    code = generate_code()
    for _ in range(max_attempts):
        try:
            if not code_exists(code):
                return code
        except Exception:
            logger.exception("new_reflection_code: uniqueness check failed; using unchecked code")
            return code
        code = generate_code()
    return code


def clean_tags(tags):
    """Keep only known tag keys, without duplicates, in CASE_TAGS order,
    at most MAX_TAGS."""
    wanted = {str(t) for t in (tags or [])}
    return [t for t in CASE_TAGS if t in wanted][:MAX_TAGS]


