"""
Reflection Records
====================

Reflection-only redesign (October 2026, agreed with the EDE team -- see
REFLECTIONS.md).

Reflection Space no longer stores case documents. A professional writes,
pastes or uploads a case, reflects on it on the spot, and only the
REFLECTION is kept (the AI's observations, questions and verified
anonymised passages -- services/findings_store.py -- plus the
professional's own private notes on them). The case text itself lives
only in the browser session while the reflection is open and is
discarded when the professional finishes or leaves.

So that reflections can still be connected to similar situations later
WITHOUT any personal identity, each reflection carries:

    reflection_code  a neutral code generated by the app (e.g. RS-7F3K2Q).
                     Never a name, a date of birth or a real file number.
    case_tags        non-personal case themes the professional ticked
                     (keys of CASE_TAGS below, e.g. "housing").
    note_type        the kind of text that was reflected on.
    previous_code    optional: the code of an earlier reflection on the
                     same situation, so the "continuity" dimension can
                     look back.

This module owns everything built on those identifiers:

- generating / validating codes and tags;
- finding a professional's OWN earlier reflections that are linked
  (previous_code chain) or similar (shared case tags), to offer as
  context for a new reflection;
- the management-only reflection listing used by Case History;
- the evidence search used by the Knowledge Assistant;
- simple counts for Research Metrics.

Privacy rules
-------------
- Similar-reflection matching for a professional only ever looks at
  THEIR OWN reflections (filtered by name in SQL). Nothing here lets one
  professional read another's reflections.
- The professional's private notes (finding_feedback) are never read by
  this module.
- Management functions require a management role (checked here, not
  only in the page) and return the AI's observations only -- never
  case text (there is none) and never anyone's notes.
- Nothing in this module writes observation text, quotes, tags or notes
  to logs -- only ids and counts.
"""

import json
